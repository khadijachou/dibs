const DICTS = { en, fr, es }

export function makeT(lang) {
  const dict = DICTS[lang] || en
  const t = (key, vars = {}) =>
    String(dict[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`))
  t.lang = DICTS[lang] ? lang : 'en'
  return t
}
